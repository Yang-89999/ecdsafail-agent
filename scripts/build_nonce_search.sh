#!/usr/bin/env bash
# Build tools/nonce_search from the challenge's own evaluator (src/bin/eval_circuit.rs, copied verbatim up to its
# main) plus tools/nonce_search/search_main.rs. Usage: scripts/build_nonce_search.sh <challenge checkout>
set -euo pipefail
. "$HOME/.cargo/env" 2>/dev/null || true
challenge="$(cd "${1:?challenge dir}" && pwd -P)"
here="$(cd "$(dirname "$0")/.." && pwd -P)"
crate="$here/tools/nonce_search"
mkdir -p "$crate/src"
python3 - "$challenge/src/bin/eval_circuit.rs" "$crate/search_main.rs" "$crate/src/main.rs" <<'PY'
import sys
src, tmpl, dst = sys.argv[1:4]
code = open(src).read()
i = code.index("\nfn main() {")
header = "// GENERATED by scripts/build_nonce_search.sh: the challenge's eval_circuit.rs up to main, then search_main.rs.\n"
open(dst, "w").write(header + "#![allow(dead_code, unused_imports)]\n" + code[:i] + "\n" + open(tmpl).read())
PY
cat > "$crate/Cargo.toml" <<TOML
[package]
name = "nonce_search"
version = "0.1.0"
edition = "2021"

[[bin]]
name = "nonce_search"
path = "src/main.rs"

[dependencies]
quantum_ecc = { path = "$challenge" }
alloy-primitives = "1.5"
sha3 = "0.10"
keccak = { version = "0.1", features = ["asm"] }
zstd = "0.13"

[profile.release]
opt-level = 3
lto = "thin"
codegen-units = 1
TOML
# Pin to the harness's dependency versions (every crate used here is already a harness dependency, so the build
# works offline in the container).
cp "$challenge/Cargo.lock" "$crate/Cargo.lock" 2>/dev/null || true
export RUSTUP_TOOLCHAIN="${RUSTUP_TOOLCHAIN:-$(sed -n 's/^[[:space:]]*channel[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' "$challenge/rust-toolchain")}"
# Built for this machine's CPU (AVX-512 Keccak on x86 when present; SHA3 instructions on Apple silicon).
export RUSTFLAGS="${RUSTFLAGS:--C target-cpu=native}"
cd "$crate"
if ! cargo build --release --offline -q 2> build-offline.log; then
  tail -5 build-offline.log >&2
  echo "offline build failed; trying with network" >&2
  cargo build --release -q || { echo "!! nonce_search build failed" >&2; exit 1; }
fi
# win_score.sh rebuilds when this stamp differs from its own (an older binary lacks crnfast or its failing-shot counts)
echo "3" > "$crate/.agentlab-version"
echo "built $crate/target/release/nonce_search"
