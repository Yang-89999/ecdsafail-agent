#!/usr/bin/env bash
# Build tools/fast_eval: the harness's own trusted evaluator with the shot count
# taken from EVAL_SHOTS and its bookkeeping files written to the current
# directory instead of the harness checkout. The source is copied from the
# challenge checkout at build time so it tracks upstream changes.
#
#   scripts/build_fast_eval.sh <challenge checkout>
set -euo pipefail
# shellcheck disable=SC1091
. "$HOME/.cargo/env" 2>/dev/null || true
challenge="$(cd "${1:?challenge dir}" && pwd -P)"
here="$(cd "$(dirname "$0")/.." && pwd -P)"
crate="$here/tools/fast_eval"
mkdir -p "$crate/src"

src="$challenge/src/bin/eval_circuit.rs"
dst="$crate/src/main.rs"
python3 - "$src" "$dst" <<'PY'
import re, sys
src, dst = sys.argv[1], sys.argv[2]
code = open(src).read()
# 1. shot count from EVAL_SHOTS (default: the official 9024)
code = code.replace(
    "const NUM_TESTS: usize = 9024;",
    "fn num_tests() -> usize { std::env::var(\"EVAL_SHOTS\").ok().and_then(|s| s.parse().ok()).unwrap_or(9024) }",
)
code = re.sub(r"\bNUM_TESTS\b", "num_tests()", code)
# 2. bookkeeping files land in the working directory, never in the harness checkout
code = code.replace('concat!(env!("CARGO_MANIFEST_DIR"), "/results.tsv")', '"results.tsv"')
code = code.replace('concat!(env!("CARGO_MANIFEST_DIR"), "/score.json")', '"score.json"')
# 3. EVAL_SALT (fresh draw): when set, the salt is mixed into the Fiat-Shamir hash after the domain tag, so the
#    same op stream is tested on an independent set of inputs. Unset, the inputs are exactly the official ones.
tag = 'hasher.update(b"quantum_ecc-fiat-shamir-v2");'
assert tag in code, "eval_circuit.rs changed: Fiat-Shamir domain tag not found"
code = code.replace(tag, tag + '\n    if let Some(s) = std::env::var("EVAL_SALT").ok().and_then(|s| s.parse::<u64>().ok()) {'
                    '\n        hasher.update(b"agentlab-fresh-draw");\n        hasher.update(&s.to_le_bytes());\n    }', 1)
# 4. draw.json: the per-draw outcome (failures counted over all shots, average Toffoli) whether the run passed or not
call = "let r = run_tests(&ops, &regs, total_qubits, num_bits, xof, num_tests());"
assert call in code, "eval_circuit.rs changed: run_tests call not found"
code = code.replace(call, call + '\n    let _ = std::fs::write("draw.json", format!("{{\\"ok\\": {}, \\"classical_failures\\": {}, '
                    '\\"phase_garbage_batches\\": {}, \\"ancilla_garbage_batches\\": {}, \\"avg_tof\\": {:.3}, \\"qubits\\": {}, '
                    '\\"shots\\": {}}}\\n", r.ok, r.classical_failures, r.phase_garbage_batches, r.ancilla_garbage_batches, '
                    'r.avg_tof, total_qubits, r.n_shots));', 1)
# 5. FAIL_LOG=<file>: append one line per failing shot (index, classical mismatch, phase bit, input points in hex),
#    so failures can be studied. Unset, nothing is written.
apply = "        sim.apply_iter(ops.iter());\n"
assert apply in code, "eval_circuit.rs changed: batch apply not found"
code = code.replace(apply, apply + (
    '        if let Ok(path) = std::env::var("FAIL_LOG") {\n'
    '            let ph = sim.phase & cond_mask;\n'
    '            let mut out = String::new();\n'
    '            for shot in 0..bs {\n'
    '                let i = batch * BATCH + shot;\n'
    '                let bad = sim.get_register(&layout_regs[0], shot) != expected[i].0 || sim.get_register(&layout_regs[1], shot) != expected[i].1;\n'
    '                let pb = (ph >> shot) & 1 == 1;\n'
    '                if bad || pb {\n'
    '                    out.push_str(&format!("{}\\t{}\\t{}\\t{:#x}\\t{:#x}\\t{:#x}\\t{:#x}\\n", i, bad as u8, pb as u8, targets[i].0, targets[i].1, offsets[i].0, offsets[i].1));\n'
    '                }\n'
    '            }\n'
    '            if !out.is_empty() {\n'
    '                if let Ok(mut f) = OpenOptions::new().create(true).append(true).open(&path) { let _ = f.write_all(out.as_bytes()); }\n'
    '            }\n'
    '        }\n'), 1)
header = "// GENERATED by scripts/build_fast_eval.sh from the challenge's src/bin/eval_circuit.rs. Do not edit.\n"
open(dst, "w").write(header + code)
PY

cat > "$crate/Cargo.toml" <<EOF
[package]
name = "fast_eval"
version = "0.1.0"
edition = "2021"

[[bin]]
name = "fast_eval"
path = "src/main.rs"

[dependencies]
quantum_ecc = { path = "$challenge" }
alloy-primitives = "1.5"
sha3 = "0.10"
zstd = "0.13"

[profile.release]
opt-level = 3
lto = "thin"
codegen-units = 1
EOF

cd "$crate"
# Pin to the harness's dependency versions.
cp "$challenge/Cargo.lock" Cargo.lock 2>/dev/null || true
export RUSTUP_TOOLCHAIN="${RUSTUP_TOOLCHAIN:-$(sed -n 's/^[[:space:]]*channel[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' "$challenge/rust-toolchain")}"
cargo build --release --offline 2>&1 | tail -3 || cargo build --release 2>&1 | tail -3
# fast_score.sh / fresh_check.sh rebuild when this stamp differs from theirs (an older binary lacks EVAL_SALT)
echo "3" > "$crate/.agentlab-version"
echo "fast_eval: $crate/target/release/fast_eval"
